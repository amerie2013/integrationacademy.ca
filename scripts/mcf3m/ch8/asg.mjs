const S = String.raw;
const FVa = (R, i, n) => (R * ((1 + i) ** n - 1)) / i;
const PVa = (R, i, n) => (R * (1 - (1 + i) ** -n)) / i;
const PMT = (PV, i, n) => (PV * i) / (1 - (1 + i) ** -n);
const bal = (PV, i, R, k) => PV * (1 + i) ** k - FVa(R, i, k);
