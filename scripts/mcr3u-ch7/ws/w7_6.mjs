const S = String.raw;
const geo = (a, r, n) => Array.from({ length: n }, (_, i) => a * r ** i);
const partial = (a, r, n) => Array.from({ length: n }, (_, i) => (r === 1 ? a * (i + 1) : (a * (r ** (i + 1) - 1)) / (r - 1)));
const f2 = (v) => (Math.round(v * 100) / 100).toFixed(2);

